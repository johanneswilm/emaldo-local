#!/usr/bin/env python3
"""Print the bridge's identity.json for the live battery.

Run on the NAS, where the fake vendor stack keeps the ids the module and Home
Assistant were given. Nothing is written to disk here and nothing is committed:
pipe it straight to the battery.

    ssh lund.fiduswriter.org 'python3 - $BATTERY_IP' < deploy/seed_identity.py \\
      | ssh emaldo-battery 'cat > /root/emaldo-local/state/identity.json && chmod 600 /root/emaldo-local/state/identity.json'

The module re-reads its e2e credentials at every login, so the ids below are
not secret-bound to the hardware; they are seeded only so that the module (and
anything that cached them) sees the same values it already has. The app-side
ends and the chat secret are issued by the bridge itself: Home Assistant is
expected to log in again after the cutover, which is what hands it the new chat
secret.
"""

import json
import re
import sys

STACK = "/var/services/homes/johanneswilm/emaldo-stack"
HOST = sys.argv[1] if len(sys.argv) > 1 else ""


def app_dev():
    """The device block the fake stack has been answering with."""
    src = open(f"{STACK}/app/fake_api.py", encoding="utf-8").read()
    m = re.search(r"APP_DEV\s*=\s*\{(.*?)\}", src, re.S)  # dict is one flat block
    if not m:
        return {}
    return dict(re.findall(r'"(\w+)":\s*"([^"]*)"', m.group(1)))


def main() -> int:
    creds = json.load(open(f"{STACK}/data/fake_api_creds.json"))
    active = json.load(open(f"{STACK}/data/e2e_active.json"))
    try:
        # Captured vendor app-side creds: the only place the account user id
        # (needed by the sell-back-to-grid command) is recorded.
        app_creds = json.load(open(f"{STACK}/data/e2e_new_creds.json"))
    except (FileNotFoundError, ValueError):
        app_creds = {}
    e2e = creds["e2e"]
    dev = app_dev()

    identity = {
        # The e2e credential block's `id` is the literal "bmt" (a type tag in
        # the vendor protocol), not the device id: the BMT id comes from the
        # device block the stack answers with.
        "device_id": dev.get("id", ""),
        "home_id": dev.get("home_id", ""),
        "model": dev.get("model", ""),
        "name": dev.get("name", ""),
        "country_code": dev.get("country_code", ""),
        "delivery_area": dev.get("delivery_area", ""),
        # Learned from the module's own login request on first contact.
        "reg_token": "",
        "e2e_id": e2e.get("id", ""),
        "group_id": e2e.get("group_id", ""),
        "end_id": e2e.get("end_id", ""),
        "end_secret": e2e.get("end_secret", ""),
        # App/home ends are kept as the stack handed them out; their secrets
        # (and the chat) are generated by the bridge and re-issued on login.
        "app_end": creds.get("app_end", ""),
        "app_end_secret": "",
        "home_end": creds.get("home_end", ""),
        "home_group_id": "",
        "home_end_secret": "",
        "user_id": app_creds.get("user_id", "") or dev.get("user_id", ""),
        "chat_secret": active.get("chat_secret", ""),
        "chat_rotated": 0,
        "prev_chat_secret": "",
        "vendor_chat_secret": "",
        "vendor_relay_host": "",
        "last_login": 0,
    }
    missing = [k for k, v in identity.items() if not v and k not in
               {"reg_token", "app_end_secret", "home_group_id", "home_end_secret",
                "name", "home_id", "user_id", "prev_chat_secret", "vendor_chat_secret",
                "vendor_relay_host", "chat_rotated", "last_login"}]
    if missing:
        print(f"missing from the stack: {', '.join(missing)}", file=sys.stderr)
    if HOST:
        print(f"# hand-out host will be {HOST}", file=sys.stderr)
    json.dump(identity, sys.stdout, indent=1)
    print()
    return 0


if __name__ == "__main__":
    sys.exit(main())
